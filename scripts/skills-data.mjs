// Writes src/lib/skills-data.ts from Zveno's skill folders, for the two carousel rows.
// Usage: npm run skills [path to Zveno/apps/desktop/resources/skills]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? process.env.ZVENO_SKILLS ?? "../Zveno/apps/desktop/resources/skills";
const PACKS = { planning: "Planning", engineering: "Engineering", frontend: "Frontend", databases: "Databases", auth: "Auth", design: "Design", testing: "Testing", video: "Motion video", "3d": "3D", writing: "Writing", research: "Research" };

const skills = [];
for (const id of readdirSync(dir).sort()) {
  const file = join(dir, id, "skill.json");
  if (!existsSync(file)) continue;
  const s = JSON.parse(readFileSync(file, "utf8"));
  const pack = PACKS[s.pack];
  if (!pack) throw new Error(`Unknown pack ${s.pack} for ${id}`);
  let desc = s.desc;
  if (!desc) {
    const md = readFileSync(join(dir, id, "SKILL.md"), "utf8");
    desc = /^description:\s*(.+)$/m.exec(md)?.[1].trim().replace(/^['"]|['"]$/g, "") ?? "";
  }
  desc = desc.replace(/`/g, "").replace(/\s*Use (it )?when.*$/i, "").trim();
  skills.push({ id: s.id, title: s.title ?? s.id, pack, core: !!s.core, desc });
}

// Core first, then the rest by Pack, dealt alternately into two rows so each row mixes Packs.
const order = [...skills].sort((a, b) => Number(b.core) - Number(a.core) || a.pack.localeCompare(b.pack) || a.id.localeCompare(b.id));
const byPack = new Map();
for (const s of order) (byPack.get(s.pack) ?? byPack.set(s.pack, []).get(s.pack)).push(s);
const mixed = [];
const queues = [...byPack.values()];
while (queues.some((q) => q.length)) for (const q of queues) if (q.length) mixed.push(q.shift());
const rowA = mixed.filter((_, i) => i % 2 === 0);
const rowB = mixed.filter((_, i) => i % 2 === 1);

const counts = {};
for (const s of skills) counts[s.pack] = (counts[s.pack] ?? 0) + 1;

const out = `// Generated by scripts/skills-data.mjs from Zveno's skill folders. Do not edit.
export type SkillItem = { id: string; title: string; pack: string; core: boolean; desc: string };
export const SKILL_COUNT = ${skills.length};
export const CORE_COUNT = ${skills.filter((s) => s.core).length};
export const PACK_COUNTS: Record<string, number> = ${JSON.stringify(counts)};
export const ROW_A: SkillItem[] = ${JSON.stringify(rowA, null, 1)};
export const ROW_B: SkillItem[] = ${JSON.stringify(rowB, null, 1)};
`;
writeFileSync("src/lib/skills-data.ts", out);
console.log(`skills: ${skills.length} (${rowA.length} + ${rowB.length})`, counts);
